#!/usr/bin/env -S uv run --locked --script
# /// script
# requires-python = ">=3.12"
# dependencies = []
# ///
"""Build release archives and the Homebrew formula for git-attributed.

    uv run --locked --script tools/release/release.py build --version v0.1.0 --out dist
    uv run --locked --script tools/release/release.py formula --version v0.1.0 \
        --checksums dist/checksums.txt --out git-attributed.rb

`build` cross-compiles static binaries for each supported platform and
packages each with LICENSE, LICENSE.upstream, and README.md into a
reproducible .tar.gz, then writes checksums.txt. `formula` renders the tap
formula from those checksums. Failures print RELEASE_REJECTED with a code.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import os
import re
import subprocess
import sys
import tarfile
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Final

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence

REPOSITORY: Final = "amichne/attributed"
MODULE: Final = "github.com/amichne/attributed"
BINARY: Final = "git-attributed"
BUNDLED: Final = ("LICENSE", "LICENSE.upstream", "README.md")
VERSION_PATTERN: Final = re.compile(r"v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)")


@dataclass(frozen=True)
class Target:
    goos: str
    goarch: str

    @property
    def label(self) -> str:
        return f"{self.goos}_{self.goarch}"


TARGETS: Final = (
    Target("darwin", "arm64"),
    Target("darwin", "amd64"),
    Target("linux", "arm64"),
    Target("linux", "amd64"),
)


class Rejected(Exception):
    """The release cannot be produced under the declared rules."""

    def __init__(self, code: str, detail: str = "") -> None:
        super().__init__(code)
        self.code = code
        self.detail = detail


def parse_version(value: str) -> str:
    if not VERSION_PATTERN.fullmatch(value):
        raise Rejected("INVALID_VERSION", value)
    return value


def archive_name(version: str, target: Target) -> str:
    return f"{BINARY}_{version}_{target.label}.tar.gz"


RELEASE_ROOT: Final = f"https://github.com/{REPOSITORY}/releases/download"
ROOT_VARIABLE: Final = "HOMEBREW_GIT_ATTRIBUTED_URL_ROOT"


def release_path(version: str, target: Target) -> str:
    """An archive's path below the release root; a mirror keeps the same layout."""
    return f"{version}/{archive_name(version, target)}"


# ---- archives ---------------------------------------------------------------


def archive(files: Mapping[str, tuple[bytes, int]], root: str, mtime: int) -> bytes:
    """A gzip tarball whose bytes depend only on names, contents, modes, and mtime."""
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.PAX_FORMAT) as tar:
        directory = tarfile.TarInfo(root)
        directory.type = tarfile.DIRTYPE
        directory.mode = 0o755
        directory.mtime = mtime
        tar.addfile(directory)
        for name in sorted(files):
            content, mode = files[name]
            info = tarfile.TarInfo(f"{root}/{name}")
            info.size = len(content)
            info.mode = mode
            info.mtime = mtime
            tar.addfile(info, io.BytesIO(content))
    compressed = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=compressed, mtime=0) as stream:
        stream.write(raw.getvalue())
    return compressed.getvalue()


def checksums(archives: Mapping[str, bytes]) -> str:
    return "".join(
        f"{hashlib.sha256(archives[name]).hexdigest()}  {name}\n" for name in sorted(archives)
    )


def parse_checksums(text: str) -> dict[str, str]:
    result: dict[str, str] = {}
    for line in text.splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})  (\S+)", line)
        if match is None:
            raise Rejected("INVALID_CHECKSUMS", line)
        result[match.group(2)] = match.group(1)
    return result


# ---- formula ----------------------------------------------------------------

FORMULA: Final = """\
# typed: strict
# frozen_string_literal: true

# This file is generated by tools/release/release.py in amichne/attributed.
class GitAttributed < Formula
  # Set {root_variable} to download the archives from a mirror of
  # {release_root} with the same layout.
  URL_ROOT = ENV.fetch("{root_variable}", "{release_root}").chomp("/").freeze

  desc "Record which lines an AI agent wrote, in Git notes beside your history"
  homepage "https://github.com/{repository}"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "#{{URL_ROOT}}/{darwin_arm64_path}"
      sha256 "{darwin_arm64_sha}"
    end
    on_intel do
      url "#{{URL_ROOT}}/{darwin_amd64_path}"
      sha256 "{darwin_amd64_sha}"
    end
  end

  on_linux do
    on_arm do
      url "#{{URL_ROOT}}/{linux_arm64_path}"
      sha256 "{linux_arm64_sha}"
    end
    on_intel do
      url "#{{URL_ROOT}}/{linux_amd64_path}"
      sha256 "{linux_amd64_sha}"
    end
  end

  def install
    bin.install "git-attributed"
    prefix.install "LICENSE.upstream"
  end

  test do
    assert_equal "git-attributed {version}\\n", shell_output("#{{bin}}/git-attributed version")
    assert_match "Comarch S.A.", shell_output("#{{bin}}/git-attributed license")
  end
end
"""


def formula(version: str, sums: Mapping[str, str]) -> str:
    fields: dict[str, str] = {
        "repository": REPOSITORY,
        "version": version,
        "root_variable": ROOT_VARIABLE,
        "release_root": RELEASE_ROOT,
    }
    for target in TARGETS:
        name = archive_name(version, target)
        if name not in sums:
            raise Rejected("MISSING_ARCHIVE", name)
        fields[f"{target.label}_path"] = release_path(version, target)
        fields[f"{target.label}_sha"] = sums[name]
    return FORMULA.format(**fields)


# ---- effects ----------------------------------------------------------------


def run(command: Sequence[str], cwd: Path, env: Mapping[str, str] | None = None) -> str:
    result = subprocess.run(
        list(command),
        cwd=cwd,
        env=dict(env) if env else None,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise Rejected("COMMAND_FAILED", f"{command[0]} {command[1]}: {result.stderr.strip()}")
    return result.stdout


def build_binary(repo: Path, version: str, target: Target, out: Path) -> bytes:
    env = dict(os.environ, GOOS=target.goos, GOARCH=target.goarch, CGO_ENABLED="0")
    ldflags = f"-s -w -X {MODULE}/internal/version.Version={version}"
    run(
        [
            "go",
            "build",
            "-trimpath",
            "-buildvcs=false",
            "-ldflags",
            ldflags,
            "-o",
            str(out),
            f"./cmd/{BINARY}",
        ],
        repo,
        env,
    )
    return out.read_bytes()


def build(repo: Path, version: str, out: Path) -> dict[str, bytes]:
    if out.exists():
        raise Rejected("OUTPUT_EXISTS", str(out))
    mtime = int(run(["git", "log", "-1", "--format=%ct"], repo).strip())
    bundled = {name: ((repo / name).read_bytes(), 0o644) for name in BUNDLED}
    archives: dict[str, bytes] = {}
    with tempfile.TemporaryDirectory(prefix="attributed-release-") as scratch:
        for target in TARGETS:
            binary = build_binary(repo, version, target, Path(scratch) / target.label / BINARY)
            root = archive_name(version, target).removesuffix(".tar.gz")
            archives[archive_name(version, target)] = archive(
                {BINARY: (binary, 0o755), **bundled}, root, mtime
            )
    out.mkdir(parents=True)
    for name, content in archives.items():
        (out / name).write_bytes(content)
    (out / "checksums.txt").write_text(checksums(archives))
    return archives


def main(argv: Sequence[str]) -> int:
    parser = argparse.ArgumentParser(description="Build git-attributed release artifacts.")
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[2])
    commands = parser.add_subparsers(dest="command", required=True)
    build_parser = commands.add_parser("build", help="build archives and checksums.txt")
    build_parser.add_argument("--version", required=True)
    build_parser.add_argument("--out", type=Path, required=True)
    formula_parser = commands.add_parser("formula", help="render the Homebrew formula")
    formula_parser.add_argument("--version", required=True)
    formula_parser.add_argument("--checksums", type=Path, required=True)
    formula_parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        version = parse_version(args.version)
        out: Path = args.out
        if args.command == "build":
            repo: Path = args.repo
            built = build(repo, version, out)
            print(f"BUILT {len(built)} archives in {out}")
        else:
            checksum_path: Path = args.checksums
            rendered = formula(version, parse_checksums(checksum_path.read_text()))
            out.write_text(rendered)
            print(f"RENDERED {out}")
    except Rejected as rejected:
        detail = f" detail={rejected.detail}" if rejected.detail else ""
        print(f"RELEASE_REJECTED code={rejected.code}{detail}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
